"""Generate dist/kaggle_notebook.py — the self-contained Kaggle submission file.

The Kaggle notebook must be a single file, so this script inlines
stability_core.py and appends the kbench task definitions. Always regenerate
after editing the core:

    python build_notebook.py
"""

from __future__ import annotations

from pathlib import Path

SRC = Path(__file__).resolve().parent
CORE = SRC / "stability_core.py"
DIST = SRC.parent / "dist"
OUT = DIST / "kaggle_notebook.py"

HEADER = '''# %% [markdown]
# # Paraphrase Stability Benchmark
# Kaggle Benchmarking Challenge submission (#kagglechallenge).
#
# Ask each of 32 items in 5 semantically-equivalent phrasings x 2 repeats
# (320 cells). Score deterministically (no LLM judge). Headline metric:
# Stability-Adjusted Accuracy (SAA) = fraction of items answered correctly
# under EVERY phrasing, with a cluster-bootstrap 95% CI.
#
# This file is generated by src/build_notebook.py — edit src/stability_core.py.
# %%
'''

TASKS = '''# %%
# ====================== kbench task definitions ======================
import os

import kaggle_benchmarks as kbench

# Keep per-cell output quiet for a 320-cell grid.
os.environ["RENDER_SUBRUNS"] = "False"

EXPECTED_CELLS = len(build_cells())


@kbench.task(name="ask_once", store_task=False)
def ask_once(llm, item_id, category, variant, repeat, seed, prompt,
             options_json, correct_letter, correct_option) -> dict:
    """One benchmark cell: prompt the model, score deterministically."""
    response = llm.prompt(
        prompt,
        seed=int(seed),
        # Kaggle proxy reserves quota against the MAX output length; capping
        # removed cost-limit failures in the reference implementation.
        extra_api_params={"max_tokens": 4096},
    )
    row = {
        "item_id": item_id,
        "category": category,
        "variant": variant,
        "repeat": repeat,
        "seed": seed,
        "correct_letter": correct_letter,
        "correct_option": correct_option,
    }
    return make_record(row, response, tuple(options_json))


@kbench.task(name="paraphrase_stability")
def paraphrase_stability(llm) -> tuple[float, float]:
    """Run the full grid; returns (SAA, 95% CI half-width) for the leaderboard."""
    problems = validate_answer_key()
    if problems:
        raise ValueError(f"answer key invalid, refusing to run: {problems}")
    df = build_cells()
    with kbench.client.enable_cache():
        results = ask_once.evaluate(
            llm=[llm],
            evaluation_data=df,
            n_jobs=8,
            timeout=300,
            on_failure="continue",   # transient API failures shouldn't kill the grid
            remove_run_files=True,   # keep only the main task's files for %choose
        )
        # Note: nested evaluations always run with max_attempts=1 (kbench
        # coerces it), so failures are reported via coverage in the metrics
        # rather than retried here.
    records = [r.result for r in results.completed_runs]
    kbench.assertions.assert_true(
        len(records) >= int(0.9 * len(df)),
        expectation=(
            f"At least 90% of the {len(df)} cells must complete "
            f"(got {len(records)})."
        ),
    )
    metrics = compute_metrics(records)
    print(format_report(metrics))
    if len(records) < len(df):
        print(f"WARNING: {len(df) - len(records)} cells errored and were excluded.")

    # Persist per-cell records + metrics as plain files. %choose only removes
    # *run.json / *task.json, so these survive and become the input to
    # analyze.py -> numbers.json -> figures -> post + paper.
    model_name = "".join(c if c.isalnum() or c in "-_." else "_" for c in
                         str(getattr(llm, "name", "unknown"))) or "unknown"
    rec_df = pd.DataFrame(records)
    rec_df["model"] = model_name
    rec_df.to_csv(f"paraphrase_records_{model_name}.csv", index=False)
    import json as _json
    metrics_out = dict(metrics)
    metrics_out["model"] = model_name
    with open(f"paraphrase_metrics_{model_name}.json", "w", encoding="utf-8") as f:
        _json.dump(metrics_out, f, indent=2, default=str, sort_keys=True)
    print(f"MODEL={model_name}")
    print("METRICS_JSON=" + _json.dumps(metrics_out, default=str, sort_keys=True))

    lo, hi = metrics["saa_ci"]
    return (metrics["saa"], (hi - lo) / 2.0)


# %% [markdown]
# Run once with the default model. On Kaggle, use "Evaluate More Models" on the
# task page to swap in additional models — no code changes needed.
# %%
paraphrase_stability.run(llm=kbench.llm)

# %%
# Select this task as the leaderboard output (Kaggle notebook magic).
%choose paraphrase_stability
'''


def build() -> Path:
    core = CORE.read_text(encoding="utf-8")
    DIST.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + core + "\n" + TASKS, encoding="utf-8")
    return OUT


if __name__ == "__main__":
    path = build()
    print(f"wrote {path} ({path.stat().st_size} bytes)")
